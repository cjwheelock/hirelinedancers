#!/usr/bin/env node

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const commercialTermsPath = resolve(repositoryRoot, "config/commercial-terms.json");
export const generatedTermsPath = resolve(repositoryRoot, "supabase/functions/_shared/hld-commercial-terms.ts");

function assertInteger(value, path, minimum = 1) {
  if (!Number.isInteger(value) || value < minimum) {
    throw new Error(`${path} must be an integer greater than or equal to ${minimum}`);
  }
}

function assertString(value, path, pattern) {
  if (typeof value !== "string" || !value.trim() || (pattern && !pattern.test(value))) {
    throw new Error(`${path} is invalid`);
  }
}

export function validateCommercialTerms(terms) {
  if (!terms || typeof terms !== "object" || Array.isArray(terms)) {
    throw new Error("Commercial terms must be a JSON object");
  }
  if (terms.schemaVersion !== 1) throw new Error("Unsupported commercial terms schemaVersion");
  assertString(terms.contractVersion, "contractVersion", /^[a-z0-9][a-z0-9-]+$/);
  assertString(terms.effectiveAt, "effectiveAt");
  if (Number.isNaN(Date.parse(terms.effectiveAt))) throw new Error("effectiveAt must be an ISO timestamp");
  if (terms.currency !== "usd") throw new Error("Only USD commercial terms are currently supported");

  assertInteger(terms.membership?.monthlyPriceCents, "membership.monthlyPriceCents");
  if (terms.membership?.billingInterval !== "month" || terms.membership?.billingIntervalCount !== 1) {
    throw new Error("The current membership contract must bill once per month");
  }
  assertString(terms.membership?.checkoutTermsVersion, "membership.checkoutTermsVersion", /^[a-z0-9][a-z0-9-]+$/);
  assertString(terms.paymentSetup?.termsVersion, "paymentSetup.termsVersion", /^[a-z0-9][a-z0-9-]+$/);

  assertString(terms.offer?.foundingOfferCode, "offer.foundingOfferCode", /^[a-z0-9]+(?:_[a-z0-9]+)*$/);
  assertString(terms.offer?.outreachOfferCode, "offer.outreachOfferCode", /^[a-z0-9]+(?:_[a-z0-9]+)*$/);
  if (terms.offer.foundingOfferCode === terms.offer.outreachOfferCode) {
    throw new Error("Founding and outreach offer codes must remain distinct");
  }
  assertInteger(terms.offer?.freeBillingCycles, "offer.freeBillingCycles");
  assertInteger(terms.offer?.foundingInstructorLimit, "offer.foundingInstructorLimit");
  assertInteger(terms.offer?.invitationClaimDays, "offer.invitationClaimDays");
  assertInteger(terms.offer?.profileSubmissionDays, "offer.profileSubmissionDays");

  assertString(terms.guarantee?.termsVersion, "guarantee.termsVersion", /^[a-z0-9][a-z0-9-]+$/);
  assertInteger(terms.guarantee?.coverageDays, "guarantee.coverageDays");
  assertInteger(terms.guarantee?.claimWindowDays, "guarantee.claimWindowDays");
  if (terms.guarantee?.startEvent !== "first_positive_paid_membership_invoice") {
    throw new Error("The guarantee start event must remain explicit");
  }
  assertInteger(terms.billingRecovery?.graceDays, "billingRecovery.graceDays");
  if (terms.billingRecovery?.eligibility !== "at_least_one_positive_paid_membership_invoice") {
    throw new Error("The billing recovery eligibility rule must remain explicit");
  }

  for (const [key, value] of Object.entries(terms.database ?? {})) {
    assertString(value, `database.${key}`, /^\d{12}_[a-z0-9_]+\.sql$/);
  }
  const requiredMigrationKeys = [
    "invitationPolicyMigration",
    "guaranteePolicyMigration",
    "paymentSetupPolicyMigration",
    "billingRecoveryPolicyMigration"
  ];
  for (const key of requiredMigrationKeys) {
    if (!terms.database?.[key]) throw new Error(`database.${key} is required`);
  }
  return terms;
}

export function loadCommercialTerms() {
  return validateCommercialTerms(JSON.parse(readFileSync(commercialTermsPath, "utf8")));
}

export function numberWord(value) {
  const words = ["zero", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine", "ten", "eleven", "twelve", "thirteen", "fourteen", "fifteen", "sixteen", "seventeen", "eighteen", "nineteen", "twenty"];
  return words[value] ?? String(value);
}

export function renderGeneratedTerms(terms) {
  const freePeriod = `${numberWord(terms.offer.freeBillingCycles)} ${terms.offer.freeBillingCycles === 1 ? "month" : "months"}`;
  const freeCycles = `${numberWord(terms.offer.freeBillingCycles)} free monthly billing ${terms.offer.freeBillingCycles === 1 ? "cycle" : "cycles"}`;
  return `// Generated by scripts/sync-commercial-terms.mjs. Do not edit by hand.\n` +
    `export const HLD_COMMERCIAL_TERMS = ${JSON.stringify(terms, null, 2)} as const;\n\n` +
    `export const MONTHLY_PRICE_CENTS = HLD_COMMERCIAL_TERMS.membership.monthlyPriceCents;\n` +
    `export const INSTRUCTOR_FOUNDING_OFFER_CODE = HLD_COMMERCIAL_TERMS.offer.foundingOfferCode;\n` +
    `export const INSTRUCTOR_OUTREACH_OFFER_CODE = HLD_COMMERCIAL_TERMS.offer.outreachOfferCode;\n` +
    `export const INSTRUCTOR_OUTREACH_OFFER_MONTHS = HLD_COMMERCIAL_TERMS.offer.freeBillingCycles;\n` +
    `export const INSTRUCTOR_OFFER_FREE_PERIOD_LABEL = ${JSON.stringify(freePeriod)};\n` +
    `export const INSTRUCTOR_OFFER_FREE_CYCLES_LABEL = ${JSON.stringify(freeCycles)};\n` +
    `export const FOUNDING_INSTRUCTOR_LIMIT = HLD_COMMERCIAL_TERMS.offer.foundingInstructorLimit;\n` +
    `export const INVITATION_CLAIM_DAYS = HLD_COMMERCIAL_TERMS.offer.invitationClaimDays;\n` +
    `export const PROFILE_SUBMISSION_DAYS = HLD_COMMERCIAL_TERMS.offer.profileSubmissionDays;\n` +
    `export const MEMBERSHIP_CHECKOUT_TERMS_VERSION = HLD_COMMERCIAL_TERMS.membership.checkoutTermsVersion;\n` +
    `export const INSTRUCTOR_PAYMENT_SETUP_TERMS_VERSION = HLD_COMMERCIAL_TERMS.paymentSetup.termsVersion;\n` +
    `export const MEMBERSHIP_GUARANTEE_TERMS_VERSION = HLD_COMMERCIAL_TERMS.guarantee.termsVersion;\n` +
    `export const GUARANTEE_COVERAGE_DAYS = HLD_COMMERCIAL_TERMS.guarantee.coverageDays;\n` +
    `export const GUARANTEE_CLAIM_WINDOW_DAYS = HLD_COMMERCIAL_TERMS.guarantee.claimWindowDays;\n` +
    `export const BILLING_RECOVERY_GRACE_DAYS = HLD_COMMERCIAL_TERMS.billingRecovery.graceDays;\n`;
}

function main() {
  const terms = loadCommercialTerms();
  const expected = renderGeneratedTerms(terms);
  if (process.argv.includes("--check")) {
    const actual = readFileSync(generatedTermsPath, "utf8");
    if (actual !== expected) {
      console.error("Generated commercial terms are stale. Run npm run terms:sync.");
      process.exit(1);
    }
    console.log(`Commercial terms generated module matches ${terms.contractVersion}.`);
    return;
  }
  writeFileSync(generatedTermsPath, expected);
  console.log(`Generated ${generatedTermsPath} from ${terms.contractVersion}.`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
