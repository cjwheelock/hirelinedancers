create or replace function public.enqueue_due_inquiry_followups()
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  booking_count integer := 0;
  completion_count integer := 0;
begin
  if auth.role() <> 'service_role' then
    raise exception 'Service role required';
  end if;

  update public.inquiry_notification_jobs job
  set status = 'canceled', completed_at = now(), locked_at = null,
      last_error = 'Follow-up is no longer needed'
  from public.inquiry_recipients recipient
  join public.inquiries inquiry on inquiry.id = recipient.inquiry_id
  where job.inquiry_recipient_id = recipient.id
    and job.status = 'pending'
    and (
      (job.notification_type = 'booking_followup' and exists (
        select 1 from public.inquiry_outcome_reports report
        join public.instructor_profiles profile on profile.account_id = report.reporter_account_id
        where report.inquiry_id = inquiry.id
          and profile.id = inquiry.instructor_profile_id
      ))
      or (
        job.notification_type = 'completion_followup'
        and (
          inquiry.booking_outcome <> 'booked'
          or inquiry.completion_status <> 'unknown'
          or inquiry.completion_next_ask_at is null
          or inquiry.completion_next_ask_at > now()
        )
      )
    );

  insert into public.inquiry_notification_jobs (
    inquiry_recipient_id, channel, notification_type, available_at
  )
  select recipient.id, 'email', 'booking_followup', now()
  from public.inquiries inquiry
  join public.inquiry_recipients recipient on recipient.inquiry_id = inquiry.id
  join public.instructor_profiles profile on profile.id = recipient.instructor_profile_id
  where inquiry.outcome_next_ask_at is not null
    and inquiry.outcome_next_ask_at <= now()
    and not exists (
      select 1
      from public.inquiry_outcome_reports report
      where report.inquiry_id = inquiry.id
        and report.reporter_account_id = profile.account_id
    )
  on conflict (inquiry_recipient_id, channel, notification_type) do update set
    status = 'pending',
    available_at = excluded.available_at,
    attempts = 0,
    locked_at = null,
    completed_at = null,
    last_error = null
  where public.inquiry_notification_jobs.status = 'canceled';
  get diagnostics booking_count = row_count;

  insert into public.inquiry_notification_jobs (
    inquiry_recipient_id, channel, notification_type, available_at
  )
  select recipient.id, 'email', 'completion_followup', now()
  from public.inquiries inquiry
  join public.inquiry_recipients recipient on recipient.inquiry_id = inquiry.id
  where recipient.instructor_profile_id is not null
    and inquiry.booking_outcome = 'booked'
    and inquiry.completion_status = 'unknown'
    and inquiry.completion_next_ask_at is not null
    and inquiry.completion_next_ask_at <= now()
  on conflict (inquiry_recipient_id, channel, notification_type) do update set
    status = 'pending',
    available_at = excluded.available_at,
    attempts = 0,
    locked_at = null,
    completed_at = null,
    last_error = null
  where public.inquiry_notification_jobs.status = 'canceled';
  get diagnostics completion_count = row_count;

  return booking_count + completion_count;
end;
$$;

create or replace function public.claim_inquiry_notification_jobs_v2(
  p_limit integer default 10,
  p_lock_timeout interval default interval '10 minutes'
)
returns table (
  job_id bigint,
  notification_type text,
  channel text,
  attempt_number integer,
  inquiry_recipient_id uuid,
  delivered_to_email text,
  delivered_to_phone_e164 text,
  inquiry_id uuid,
  instructor_name text,
  organizer_name text,
  organizer_email text,
  company_name text,
  event_type text,
  event_date date,
  event_start_time time,
  time_zone text,
  venue_name text,
  event_location text,
  guest_count integer,
  budget_range text,
  music_requests text,
  venue_has_speakers boolean,
  venue_has_microphone boolean,
  inquiry_message text
)
language sql
security definer
set search_path = public
as $$
  with exhausted as (
    update public.inquiry_notification_jobs job
    set status = 'failed',
        completed_at = now(),
        locked_at = null,
        last_error = coalesce(job.last_error, 'Worker stopped before the final attempt completed')
    where job.status = 'processing'
      and job.attempts >= 6
      and coalesce(job.locked_at, '-infinity'::timestamptz)
        < now() - greatest(p_lock_timeout, interval '1 minute')
    returning job.inquiry_recipient_id, job.channel, job.notification_type
  ), exhausted_recipients as (
    update public.inquiry_recipients recipient
    set email_delivery_status = case
          when exists (
            select 1 from exhausted
            where exhausted.inquiry_recipient_id = recipient.id
              and exhausted.channel = 'email'
              and exhausted.notification_type = 'new_inquiry'
          ) then 'failed'
          else recipient.email_delivery_status
        end,
        sms_delivery_status = case
          when exists (
            select 1 from exhausted
            where exhausted.inquiry_recipient_id = recipient.id
              and exhausted.channel = 'sms'
              and exhausted.notification_type = 'new_inquiry'
          ) then 'failed'
          else recipient.sms_delivery_status
        end,
        updated_at = now()
    where exists (
      select 1 from exhausted
      where exhausted.inquiry_recipient_id = recipient.id
        and exhausted.notification_type = 'new_inquiry'
    )
    returning recipient.id
  ), candidates as (
    select job.id
    from public.inquiry_notification_jobs job
    where job.attempts < 6
      and (
        (job.status = 'pending' and job.available_at <= now())
        or (
          job.status = 'processing'
          and coalesce(job.locked_at, '-infinity'::timestamptz)
            < now() - greatest(p_lock_timeout, interval '1 minute')
        )
      )
    order by job.available_at, job.id
    for update skip locked
    limit greatest(1, least(coalesce(p_limit, 10), 25))
  ), claimed as (
    update public.inquiry_notification_jobs job
    set status = 'processing',
        attempts = job.attempts + 1,
        locked_at = now(),
        last_error = null
    from candidates
    where job.id = candidates.id
    returning job.*
  )
  select
    claimed.id,
    claimed.notification_type,
    claimed.channel,
    claimed.attempts,
    recipient.id,
    case
      when claimed.notification_type = 'new_inquiry' then recipient.delivered_to_email
      else coalesce(settings.inquiry_email, recipient.delivered_to_email)
    end,
    case
      when claimed.notification_type = 'new_inquiry' then recipient.delivered_to_phone_e164
      else coalesce(settings.inquiry_phone_e164, recipient.delivered_to_phone_e164)
    end,
    inquiry.id,
    coalesce(profile.display_name, inquiry.instructor_name, 'Line dance instructor'),
    coalesce(inquiry.contact_name, inquiry.name),
    coalesce(inquiry.contact_email, inquiry.email),
    inquiry.company_name,
    inquiry.event_type,
    coalesce(inquiry.booking_event_date, inquiry.event_date),
    inquiry.event_start_time,
    inquiry.time_zone,
    inquiry.venue_name,
    coalesce(inquiry.location, concat_ws(', ', inquiry.event_city, inquiry.event_region)),
    inquiry.guest_count,
    inquiry.budget_range,
    inquiry.music_requests,
    inquiry.venue_has_speakers,
    inquiry.venue_has_microphone,
    inquiry.message
  from claimed
  join public.inquiry_recipients recipient on recipient.id = claimed.inquiry_recipient_id
  join public.inquiries inquiry on inquiry.id = recipient.inquiry_id
  left join public.instructor_profiles profile on profile.id = recipient.instructor_profile_id
  left join public.instructor_private_settings settings
    on settings.instructor_profile_id = recipient.instructor_profile_id;
$$;

create or replace function public.complete_inquiry_notification_job(
  p_job_id bigint,
  p_success boolean,
  p_provider_message_id text default null,
  p_error text default null,
  p_retryable boolean default false
)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  job public.inquiry_notification_jobs;
  next_status text;
  retry_seconds integer;
  related_inquiry_id uuid;
begin
  select * into job
  from public.inquiry_notification_jobs
  where id = p_job_id
  for update;

  if job.id is null then
    raise exception 'Notification job not found';
  end if;
  if job.status = 'sent' then
    return 'sent';
  end if;
  if job.status <> 'processing' then
    raise exception 'Notification job is not processing';
  end if;

  select inquiry_id into related_inquiry_id
  from public.inquiry_recipients
  where id = job.inquiry_recipient_id;

  if p_success then
    next_status := 'sent';
    update public.inquiry_notification_jobs
    set status = 'sent',
        provider_message_id = nullif(trim(p_provider_message_id), ''),
        sent_at = now(),
        completed_at = now(),
        locked_at = null,
        last_error = null
    where id = job.id;

    if job.notification_type = 'new_inquiry' then
      if job.channel = 'email' then
        update public.inquiry_recipients
        set email_delivery_status = 'sent',
            email_provider_message_id = nullif(trim(p_provider_message_id), ''),
            updated_at = now()
        where id = job.inquiry_recipient_id;
      else
        update public.inquiry_recipients
        set sms_delivery_status = 'sent',
            sms_provider_message_id = nullif(trim(p_provider_message_id), ''),
            updated_at = now()
        where id = job.inquiry_recipient_id;
      end if;
    elsif job.notification_type = 'booking_followup' then
      update public.inquiries
      set outcome_followup_count = outcome_followup_count + 1,
          outcome_last_asked_at = now(),
          outcome_next_ask_at = null
      where id = related_inquiry_id;
    elsif job.notification_type = 'completion_followup' then
      update public.inquiries
      set completion_followup_count = completion_followup_count + 1,
          completion_last_asked_at = now(),
          completion_next_ask_at = null
      where id = related_inquiry_id;
    end if;
  elsif p_retryable and job.attempts < 6 then
    next_status := 'pending';
    retry_seconds := least(1800, (30 * power(2, greatest(job.attempts - 1, 0)))::integer);

    update public.inquiry_notification_jobs
    set status = 'pending',
        available_at = now() + retry_seconds * interval '1 second',
        locked_at = null,
        last_error = left(coalesce(p_error, 'Provider request failed'), 2000)
    where id = job.id;

    if job.notification_type = 'new_inquiry' then
      if job.channel = 'email' then
        update public.inquiry_recipients
        set email_delivery_status = 'queued', updated_at = now()
        where id = job.inquiry_recipient_id;
      else
        update public.inquiry_recipients
        set sms_delivery_status = 'queued', updated_at = now()
        where id = job.inquiry_recipient_id;
      end if;
    end if;
  else
    next_status := 'failed';
    update public.inquiry_notification_jobs
    set status = 'failed',
        completed_at = now(),
        locked_at = null,
        last_error = left(coalesce(p_error, 'Provider request failed'), 2000)
    where id = job.id;

    if job.notification_type = 'new_inquiry' then
      if job.channel = 'email' then
        update public.inquiry_recipients
        set email_delivery_status = 'failed', updated_at = now()
        where id = job.inquiry_recipient_id;
      else
        update public.inquiry_recipients
        set sms_delivery_status = 'failed', updated_at = now()
        where id = job.inquiry_recipient_id;
      end if;
    end if;
  end if;

  return next_status;
end;
$$;

create or replace function public.defer_inquiry_notification_job(
  p_job_id bigint,
  p_error text,
  p_delay interval default interval '15 minutes'
)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  job public.inquiry_notification_jobs;
begin
  select * into job
  from public.inquiry_notification_jobs
  where id = p_job_id
  for update;

  if job.id is null then
    raise exception 'Notification job not found';
  end if;
  if job.status = 'sent' then
    return 'sent';
  end if;
  if job.status <> 'processing' then
    raise exception 'Notification job is not processing';
  end if;

  update public.inquiry_notification_jobs
  set status = 'pending',
      attempts = greatest(attempts - 1, 0),
      available_at = now() + greatest(p_delay, interval '1 minute'),
      locked_at = null,
      last_error = left(coalesce(p_error, 'Notification provider is not configured'), 2000)
  where id = job.id;

  if job.notification_type = 'new_inquiry' then
    if job.channel = 'email' then
      update public.inquiry_recipients
      set email_delivery_status = 'queued', updated_at = now()
      where id = job.inquiry_recipient_id;
    else
      update public.inquiry_recipients
      set sms_delivery_status = 'queued', updated_at = now()
      where id = job.inquiry_recipient_id;
    end if;
  end if;

  return 'pending';
end;
$$;

drop function if exists public.get_marketplace_admin_analytics(timestamptz, timestamptz, text);
create or replace function public.get_marketplace_admin_analytics(
  p_start timestamptz default null,
  p_end timestamptz default null,
  p_bucket text default 'day',
  p_time_zone text default 'America/New_York'
)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  result jsonb;
  resolved_time_zone text;
begin
  if not public.is_marketplace_admin() then
    raise exception 'Administrator access required';
  end if;
  if p_start is not null and p_end is not null and p_start >= p_end then
    raise exception 'The start date must be before the end date';
  end if;
  if p_bucket not in ('day', 'week', 'month', 'year') then
    raise exception 'Invalid reporting interval';
  end if;

  select timezone.name into resolved_time_zone
  from pg_catalog.pg_timezone_names timezone
  where timezone.name = p_time_zone
  limit 1;
  resolved_time_zone := coalesce(resolved_time_zone, 'America/New_York');

  with filtered as (
    select inquiry.*
    from public.inquiries inquiry
    where (p_start is null or inquiry.created_at >= p_start)
      and (p_end is null or inquiry.created_at < p_end)
  ), outcome_activity as (
    select inquiry.*
    from public.inquiries inquiry
    where inquiry.outcome_reported_at is not null
      and (p_start is null or inquiry.outcome_reported_at >= p_start)
      and (p_end is null or inquiry.outcome_reported_at < p_end)
  ), completion_activity as (
    select inquiry.*, completion_event.occurred_at as completion_occurred_at
    from public.inquiries inquiry
    cross join lateral (
      select coalesce(
        (
          (coalesce(inquiry.booking_event_date, inquiry.event_date) + time '12:00')
          at time zone coalesce(
            (
              select timezone.name
              from pg_catalog.pg_timezone_names timezone
              where timezone.name = inquiry.time_zone
              limit 1
            ),
            resolved_time_zone
          )
        ),
        inquiry.completion_reported_at
      ) as occurred_at
    ) completion_event
    where inquiry.completion_status <> 'unknown'
      and completion_event.occurred_at is not null
      and (p_start is null or completion_event.occurred_at >= p_start)
      and (p_end is null or completion_event.occurred_at < p_end)
  ), summary as (
    select
      (select count(*)::integer from filtered) as inquiries,
      (select count(distinct coalesce(instructor_profile_id::text, instructor_slug))::integer from filtered) as instructors,
      (select count(distinct coalesce(
        'company:' || lower(nullif(trim(company_name), '')),
        'account:' || organizer_account_id::text
      ))::integer from filtered) as companies,
      (select count(*)::integer from outcome_activity where booking_outcome = 'booked') as booked,
      (select count(*)::integer from filtered where booking_outcome = 'still_deciding') as in_progress,
      (select count(*)::integer from outcome_activity where booking_outcome = 'not_booked') as not_booked,
      (select count(*)::integer from completion_activity where completion_status = 'completed') as completed,
      (select count(*)::integer from completion_activity where completion_status = 'did_not_happen') as did_not_happen,
      (select count(*)::integer from filtered where booking_outcome = 'booked') as cohort_booked,
      (select count(*)::integer from filtered where completion_status = 'completed') as cohort_completed
  ), instructor_rows as (
    select
      coalesce(filtered.instructor_profile_id::text, filtered.instructor_slug, 'unknown') as instructor_key,
      coalesce(profile.display_name, max(filtered.instructor_name), 'Unknown instructor') as instructor_name,
      count(*)::integer as inquiries,
      count(distinct coalesce(
        'company:' || lower(nullif(trim(filtered.company_name), '')),
        'account:' || filtered.organizer_account_id::text
      ))::integer as companies,
      count(*) filter (where filtered.booking_outcome = 'booked')::integer as booked,
      count(*) filter (where filtered.completion_status = 'completed')::integer as completed,
      max(filtered.created_at) as latest_inquiry_at
    from filtered
    left join public.instructor_profiles profile on profile.id = filtered.instructor_profile_id
    group by coalesce(filtered.instructor_profile_id::text, filtered.instructor_slug, 'unknown'), profile.display_name
  ), company_rows as (
    select
      coalesce(
        'company:' || lower(nullif(trim(filtered.company_name), '')),
        'account:' || filtered.organizer_account_id::text
      ) as company_key,
      coalesce(
        max(nullif(trim(filtered.company_name), '')),
        max(nullif(trim(filtered.contact_name), '')),
        'Individual organizer'
      ) as company_name,
      max(filtered.contact_email) as contact_email,
      count(*)::integer as inquiries,
      count(distinct coalesce(filtered.instructor_profile_id::text, filtered.instructor_slug))::integer as instructors,
      count(*) filter (where filtered.booking_outcome = 'booked')::integer as booked,
      count(*) filter (where filtered.completion_status = 'completed')::integer as completed,
      max(filtered.created_at) as latest_inquiry_at
    from filtered
    group by coalesce(
      'company:' || lower(nullif(trim(filtered.company_name), '')),
      'account:' || filtered.organizer_account_id::text
    )
  ), instructor_company_rows as (
    select
      coalesce(filtered.instructor_profile_id::text, filtered.instructor_slug, 'unknown') as instructor_key,
      coalesce(profile.display_name, max(filtered.instructor_name), 'Unknown instructor') as instructor_name,
      coalesce(
        'company:' || lower(nullif(trim(filtered.company_name), '')),
        'account:' || filtered.organizer_account_id::text
      ) as company_key,
      coalesce(
        max(nullif(trim(filtered.company_name), '')),
        max(nullif(trim(filtered.contact_name), '')),
        'Individual organizer'
      ) as company_name,
      max(filtered.contact_email) as contact_email,
      count(*)::integer as inquiries,
      count(*) filter (where filtered.booking_outcome = 'booked')::integer as booked,
      count(*) filter (where filtered.completion_status = 'completed')::integer as completed,
      max(filtered.created_at) as latest_inquiry_at
    from filtered
    left join public.instructor_profiles profile on profile.id = filtered.instructor_profile_id
    group by
      coalesce(filtered.instructor_profile_id::text, filtered.instructor_slug, 'unknown'),
      profile.display_name,
      coalesce(
        'company:' || lower(nullif(trim(filtered.company_name), '')),
        'account:' || filtered.organizer_account_id::text
      )
  ), activity_rows as (
    select created_at as occurred_at, 1 as inquiries, 0 as booked, 0 as completed
    from filtered
    union all
    select outcome_reported_at, 0, 1, 0
    from outcome_activity
    where booking_outcome = 'booked'
    union all
    select completion_occurred_at, 0, 0, 1
    from completion_activity
    where completion_status = 'completed'
  ), series_rows as (
    select
      date_trunc(p_bucket, activity_rows.occurred_at at time zone resolved_time_zone)::date as period_start,
      sum(activity_rows.inquiries)::integer as inquiries,
      sum(activity_rows.booked)::integer as booked,
      sum(activity_rows.completed)::integer as completed
    from activity_rows
    group by date_trunc(p_bucket, activity_rows.occurred_at at time zone resolved_time_zone)::date
  )
  select jsonb_build_object(
    'summary', coalesce((select to_jsonb(summary) from summary), '{}'::jsonb),
    'instructors', coalesce((
      select jsonb_agg(to_jsonb(instructor_rows) order by inquiries desc, instructor_name)
      from instructor_rows
    ), '[]'::jsonb),
    'companies', coalesce((
      select jsonb_agg(to_jsonb(company_rows) order by inquiries desc, company_name)
      from company_rows
    ), '[]'::jsonb),
    'instructor_companies', coalesce((
      select jsonb_agg(to_jsonb(instructor_company_rows) order by inquiries desc, instructor_name, company_name)
      from instructor_company_rows
    ), '[]'::jsonb),
    'series', coalesce((
      select jsonb_agg(to_jsonb(series_rows) order by period_start)
      from series_rows
    ), '[]'::jsonb)
  ) into result;

  return result;
end;
$$;

