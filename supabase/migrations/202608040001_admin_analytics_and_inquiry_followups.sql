create table if not exists public.marketplace_admins (
  account_id uuid primary key references public.accounts(id) on delete cascade,
  is_owner boolean not null default false,
  granted_by uuid references public.accounts(id) on delete set null,
  granted_at timestamptz not null default now()
);

create table if not exists public.marketplace_admin_events (
  id bigint generated by default as identity primary key,
  actor_account_id uuid references public.accounts(id) on delete set null,
  target_account_id uuid references public.accounts(id) on delete set null,
  action text not null,
  created_at timestamptz not null default now(),
  constraint marketplace_admin_events_action_check check (action in ('granted', 'revoked'))
);

-- Preserve the current administrator as the permanent owner during the move
-- from a single account role to independently granted admin access.
insert into public.marketplace_admins (account_id, is_owner, granted_by)
select id, true, id
from public.accounts
where role = 'admin'
on conflict (account_id) do update set is_owner = true;

create or replace function public.is_marketplace_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.accounts account
    where account.id = auth.uid()
      and (
        account.role = 'admin'
        or exists (
          select 1
          from public.marketplace_admins admin_access
          where admin_access.account_id = account.id
        )
      )
  );
$$;

create or replace function public.current_marketplace_admin_status()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select public.is_marketplace_admin();
$$;

create or replace function public.current_marketplace_owner_status()
