create or replace function public.list_marketplace_admins()
returns table (
  account_id uuid,
  email text,
  full_name text,
  is_owner boolean,
  granted_at timestamptz
)
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  if not public.is_marketplace_admin() then
    raise exception 'Administrator access required';
  end if;

  return query
  select
    access.account_id,
    account.email,
    account.full_name,
    access.is_owner,
    access.granted_at
  from public.marketplace_admins access
  join public.accounts account on account.id = access.account_id
  order by access.is_owner desc, lower(coalesce(account.full_name, account.email, ''));
end;
$$;

create or replace function public.grant_marketplace_admin(p_email text)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  target public.accounts;
begin
  if not public.current_marketplace_owner_status() then
    raise exception 'Marketplace owner access required';
  end if;
  if nullif(trim(p_email), '') is null then
    raise exception 'Email is required';
  end if;

  select * into target
  from public.accounts
  where lower(email) = lower(trim(p_email))
  limit 1;

  if target.id is null then
    raise exception 'That person must sign in to Hire Line Dancers once before you can grant admin access';
  end if;

  insert into public.marketplace_admins (account_id, is_owner, granted_by)
  values (target.id, false, auth.uid())
  on conflict (account_id) do nothing;

  if found then
    insert into public.marketplace_admin_events (actor_account_id, target_account_id, action)
    values (auth.uid(), target.id, 'granted');
  end if;

  return target.id;
end;
$$;

create or replace function public.revoke_marketplace_admin(p_account_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  target public.marketplace_admins;
begin
  if not public.current_marketplace_owner_status() then
    raise exception 'Marketplace owner access required';
  end if;
  if p_account_id = auth.uid() then
    raise exception 'You cannot revoke your own admin access';
  end if;

  select * into target
  from public.marketplace_admins
  where account_id = p_account_id
  for update;

  if target.account_id is null then
    raise exception 'Admin access record not found';
  end if;
  if target.is_owner then
    raise exception 'The marketplace owner cannot be removed';
  end if;

  delete from public.marketplace_admins where account_id = p_account_id;
  insert into public.marketplace_admin_events (actor_account_id, target_account_id, action)
  values (auth.uid(), p_account_id, 'revoked');
end;
$$;

