create or replace function public.sync_inquiry_completion_schedule()
returns trigger
language plpgsql
as $$
declare
  resolved_event_date date;
  resolved_time_zone text;
begin
  if new.booking_outcome = 'booked' and new.completion_status = 'unknown' then
    resolved_event_date := coalesce(new.booking_event_date, new.event_date);
    new.booking_event_date := resolved_event_date;
    if resolved_event_date is not null then
      select timezone.name into resolved_time_zone
      from pg_catalog.pg_timezone_names timezone
      where timezone.name = new.time_zone
      limit 1;
      resolved_time_zone := coalesce(resolved_time_zone, 'America/New_York');
      new.completion_next_ask_at :=
        ((resolved_event_date + 2 + time '10:00') at time zone resolved_time_zone);
    end if;
  elsif new.booking_outcome <> 'booked' then
    new.completion_next_ask_at := null;
  end if;
  return new;
end;
$$;

