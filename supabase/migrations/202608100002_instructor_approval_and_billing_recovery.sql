create or replace function public.preserve_profile_during_billing_grace()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if old.status = 'published' and new.status = 'approved' and exists (
    select 1
    from public.instructor_billing_recoveries recovery
    where recovery.instructor_profile_id = old.id
      and recovery.status = 'grace_period'
      and recovery.grace_ends_at > now()
  ) then
    new.status := 'published';
    new.published_at := old.published_at;
  end if;
  return new;
end;
$$;

