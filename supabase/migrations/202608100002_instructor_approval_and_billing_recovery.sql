  before update of status on public.instructor_profiles
  for each row execute function public.preserve_profile_during_billing_grace();

create or replace function public.begin_instructor_billing_recovery(
  p_event_id text,
  p_instructor_profile_id uuid,
  p_stripe_customer_id text,
  p_stripe_subscription_id text,
  p_stripe_invoice_id text,
  p_failed_at timestamptz
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  recovery public.instructor_billing_recoveries;
  has_paid boolean;
  recipient_email text;
  next_status text;
  next_grace_ends_at timestamptz;
  notification_type text;
begin
  if auth.role() <> 'service_role' then
    raise exception 'Service role required';
  end if;
  if nullif(trim(p_event_id), '') is null
    or p_instructor_profile_id is null
    or p_stripe_customer_id is null
    or p_stripe_customer_id !~ '^cus_[A-Za-z0-9]+$'
    or p_stripe_subscription_id is null
    or p_stripe_subscription_id !~ '^sub_[A-Za-z0-9]+$'
    or p_stripe_invoice_id is null
    or p_stripe_invoice_id !~ '^in_[A-Za-z0-9]+$'
    or p_failed_at is null then
    raise exception 'Billing recovery facts are invalid';
  end if;

  perform pg_advisory_xact_lock(
    hashtextextended(p_instructor_profile_id::text, 0)
  );

  if exists (
    select 1
    from public.instructor_lifetime_access access
    where access.instructor_profile_id = p_instructor_profile_id
  ) then
    return jsonb_build_object('result', 'lifetime_access_ignored');
  end if;

  if not exists (
    select 1
    from public.instructor_memberships membership
    where membership.instructor_profile_id = p_instructor_profile_id
      and membership.stripe_customer_id = p_stripe_customer_id
      and membership.stripe_subscription_id = p_stripe_subscription_id
  ) then
    raise exception 'Billing recovery does not match the instructor membership';
  end if;

  select recovery_record.* into recovery
  from public.instructor_billing_recoveries recovery_record
  where recovery_record.initial_stripe_invoice_id = p_stripe_invoice_id
     or (
       recovery_record.instructor_profile_id = p_instructor_profile_id
       and recovery_record.status in ('grace_period', 'access_paused')
     )
  order by
    (recovery_record.initial_stripe_invoice_id = p_stripe_invoice_id) desc,
    recovery_record.created_at desc
  limit 1
  for update;

  if recovery.id is not null then
    if recovery.stripe_customer_id is distinct from p_stripe_customer_id
      or recovery.stripe_subscription_id is distinct from
        p_stripe_subscription_id then
      raise exception 'Billing recovery was recorded with different Stripe facts';
    end if;

    if recovery.status not in ('grace_period', 'access_paused') then
      return jsonb_build_object(
        'result', 'closed_event_ignored',
        'recoveryId', recovery.id,
        'status', recovery.status
      );
    end if;

    if recovery.last_stripe_event_id = trim(p_event_id) then
      return jsonb_build_object(
        'result', 'duplicate',
        'recoveryId', recovery.id,
        'status', recovery.status,
        'graceEndsAt', recovery.grace_ends_at,
        'hasPriorSuccessfulPayment', recovery.has_prior_successful_payment
      );
    end if;

    update public.instructor_billing_recoveries
    set latest_stripe_invoice_id = p_stripe_invoice_id,
        last_failed_at = greatest(last_failed_at, p_failed_at),
        failure_count = failure_count + 1,
        last_stripe_event_id = trim(p_event_id),
        updated_at = now()
    where id = recovery.id
    returning * into recovery;

    return jsonb_build_object(
      'result', 'existing',
      'recoveryId', recovery.id,
      'status', recovery.status,
      'graceEndsAt', recovery.grace_ends_at,
      'hasPriorSuccessfulPayment', recovery.has_prior_successful_payment
    );
  end if;

  select exists (
    select 1
    from public.membership_paid_invoices invoice
    where invoice.instructor_profile_id = p_instructor_profile_id
  ) into has_paid;

  next_status := case when has_paid then 'grace_period' else 'access_paused' end;
  next_grace_ends_at := case
    when has_paid then p_failed_at + interval '14 days'
    else null
  end;

  insert into public.instructor_billing_recoveries (
    instructor_profile_id,
    stripe_customer_id,
    stripe_subscription_id,
    initial_stripe_invoice_id,
    latest_stripe_invoice_id,
    status,
    has_prior_successful_payment,
    first_failed_at,
    last_failed_at,
    grace_ends_at,
    access_paused_at,
    last_stripe_event_id
  ) values (
    p_instructor_profile_id,
    p_stripe_customer_id,
    p_stripe_subscription_id,
    p_stripe_invoice_id,
    p_stripe_invoice_id,
    next_status,
    has_paid,
    p_failed_at,
    p_failed_at,
    next_grace_ends_at,
    case when has_paid then null else p_failed_at end,
    trim(p_event_id)
  ) returning * into recovery;

  if has_paid then
    update public.instructor_profiles
    set status = 'published',
        published_at = coalesce(published_at, now()),
        updated_at = now()
    where id = p_instructor_profile_id
      and approved_at is not null
      and status = 'approved';
    notification_type := 'billing_grace_started';
  else
    update public.instructor_profiles
    set status = 'approved',
        updated_at = now()
    where id = p_instructor_profile_id
      and status = 'published';
    notification_type := 'billing_access_paused';
  end if;

  insert into public.membership_admin_events (
    instructor_profile_id,
    event_type,
    detail
  ) values (
    p_instructor_profile_id,
    case when has_paid
      then 'billing_grace_started'
      else 'first_payment_failed'
    end,
    jsonb_build_object(
      'recovery_id', recovery.id,
      'stripe_invoice_id', p_stripe_invoice_id,
      'grace_ends_at', next_grace_ends_at,
      'has_prior_successful_payment', has_paid
    )
  );

  select lower(trim(account.email)) into recipient_email
  from public.instructor_profiles profile
  join public.accounts account on account.id = profile.account_id
  where profile.id = p_instructor_profile_id;

  if recipient_email is not null
    and recipient_email ~ '^[^[:space:]@]+@[^[:space:]@]+[.][^[:space:]@]+$' then
    insert into public.instructor_service_notification_jobs (
      instructor_profile_id,
      billing_recovery_id,
      notification_type,
      dedupe_key,
      delivered_to_email,
      login_email
    ) values (
      p_instructor_profile_id,
      recovery.id,
      notification_type,
      recovery.id::text,
      recipient_email,
      recipient_email
    ) on conflict (notification_type, dedupe_key) do nothing;
  end if;

  return jsonb_build_object(
    'result', 'created',
    'recoveryId', recovery.id,
    'status', recovery.status,
    'graceEndsAt', recovery.grace_ends_at,
    'hasPriorSuccessfulPayment', recovery.has_prior_successful_payment
  );
end;
$$;

create or replace function public.resolve_instructor_billing_recovery(
  p_instructor_profile_id uuid,
  p_stripe_subscription_id text,
  p_stripe_invoice_id text,
  p_recovered_at timestamptz
)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  recovery_id uuid;
begin
  if auth.role() <> 'service_role' then
    raise exception 'Service role required';
  end if;
  if p_instructor_profile_id is null
    or p_stripe_subscription_id is null
    or p_stripe_subscription_id !~ '^sub_[A-Za-z0-9]+$'
    or p_stripe_invoice_id is null
    or p_stripe_invoice_id !~ '^in_[A-Za-z0-9]+$'
    or p_recovered_at is null then
    raise exception 'Billing recovery resolution facts are invalid';
  end if;

  perform pg_advisory_xact_lock(
    hashtextextended(p_instructor_profile_id::text, 0)
  );

  if not exists (
    select 1
    from public.membership_paid_invoices invoice
    where invoice.instructor_profile_id = p_instructor_profile_id
      and invoice.stripe_subscription_id = p_stripe_subscription_id
      and invoice.stripe_invoice_id = p_stripe_invoice_id
  ) then
    return 'paid_invoice_not_recorded';
  end if;

  select recovery.id into recovery_id
  from public.instructor_billing_recoveries recovery
  where recovery.instructor_profile_id = p_instructor_profile_id
    and recovery.stripe_subscription_id = p_stripe_subscription_id
    and recovery.status in ('grace_period', 'access_paused')
    and p_stripe_invoice_id in (
      recovery.initial_stripe_invoice_id,
      recovery.latest_stripe_invoice_id
    )
  limit 1
  for update;

  if recovery_id is null then
    return 'no_open_recovery';
  end if;

  update public.instructor_billing_recoveries
  set status = 'recovered',
      recovered_at = p_recovered_at,
      updated_at = now()
  where id = recovery_id;

  update public.instructor_profiles profile
  set status = 'published',
      published_at = coalesce(profile.published_at, now()),
      updated_at = now()
  where profile.id = p_instructor_profile_id
    and profile.approved_at is not null
    and profile.status = 'approved'
    and exists (
      select 1
      from public.instructor_memberships membership
      where membership.instructor_profile_id = profile.id
        and membership.stripe_subscription_id = p_stripe_subscription_id
        and membership.status in ('active', 'trialing')
    );

  insert into public.membership_admin_events (
    instructor_profile_id,
    event_type,
    detail
  ) values (
    p_instructor_profile_id,
    'billing_recovered',
    jsonb_build_object(
      'recovery_id', recovery_id,
      'stripe_invoice_id', p_stripe_invoice_id
    )
  );

  return 'recovered';
end;
$$;

create or replace function public.close_instructor_billing_recovery(
  p_instructor_profile_id uuid,
  p_stripe_subscription_id text,
  p_reason text,
  p_closed_at timestamptz
)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  updated_count integer;
begin
  if auth.role() <> 'service_role' then
    raise exception 'Service role required';
  end if;
  if p_instructor_profile_id is null
    or p_stripe_subscription_id is null
    or p_stripe_subscription_id !~ '^sub_[A-Za-z0-9]+$'
    or nullif(trim(p_reason), '') is null
    or p_closed_at is null then
    raise exception 'Billing recovery closure facts are invalid';
  end if;

  perform pg_advisory_xact_lock(
    hashtextextended(p_instructor_profile_id::text, 0)
  );

  update public.instructor_billing_recoveries
  set status = 'closed',
      closed_at = p_closed_at,
      updated_at = now()
  where instructor_profile_id = p_instructor_profile_id
    and stripe_subscription_id = p_stripe_subscription_id
    and status in ('grace_period', 'access_paused');

  get diagnostics updated_count = row_count;
  if updated_count = 0 then
    return 'no_open_recovery';
  end if;

  update public.instructor_profiles
  set status = 'approved',
      updated_at = now()
  where id = p_instructor_profile_id
    and status = 'published';

  insert into public.membership_admin_events (
    instructor_profile_id,
    event_type,
    detail
  ) values (
    p_instructor_profile_id,
    'billing_recovery_closed',
    jsonb_build_object('reason', trim(p_reason))
  );

  return 'closed';
end;
$$;

create or replace function public.expire_instructor_billing_grace_periods()
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  recovery public.instructor_billing_recoveries;
  expired_count integer := 0;
begin
  if auth.role() <> 'service_role' then
    raise exception 'Service role required';
  end if;

  for recovery in
    select recovery_record.*
    from public.instructor_billing_recoveries recovery_record
    where recovery_record.status = 'grace_period'
      and recovery_record.grace_ends_at <= now()
    order by recovery_record.grace_ends_at, recovery_record.id
    for update skip locked
  loop
    perform pg_advisory_xact_lock(
      hashtextextended(recovery.instructor_profile_id::text, 0)
    );

    update public.instructor_billing_recoveries
    set status = 'access_paused',
        access_paused_at = now(),
        updated_at = now()
    where id = recovery.id
      and status = 'grace_period';

    if found then
      update public.instructor_profiles
      set status = 'approved',
          updated_at = now()
      where id = recovery.instructor_profile_id
        and status = 'published';

      insert into public.membership_admin_events (
        instructor_profile_id,
        event_type,
        detail
      ) values (
        recovery.instructor_profile_id,
        'billing_grace_expired',
        jsonb_build_object(
          'recovery_id', recovery.id,
          'grace_ended_at', recovery.grace_ends_at
        )
      );

      expired_count := expired_count + 1;
    end if;
  end loop;

  return expired_count;
end;
$$;

create or replace function public.claim_instructor_service_notification_jobs(
  p_limit integer default 10,
  p_lock_timeout interval default interval '10 minutes'
)
returns table (
  job_id bigint,
  attempt_number integer,
  notification_type text,
  instructor_profile_id uuid,
  billing_recovery_id uuid,
  delivered_to_email text,
  login_email text,
  display_name text,
  profile_slug text,
  recovery_status text,
  has_prior_successful_payment boolean,
  first_failed_at timestamptz,
  grace_ends_at timestamptz
)
language sql
security definer
set search_path = public
as $$
  with suppressed as (
    update public.instructor_service_notification_jobs job
    set status = 'canceled',
        completed_at = now(),
        locked_at = null,
        last_error = 'Billing issue was resolved before the email was sent'
    where job.status in ('pending', 'processing')
      and job.billing_recovery_id is not null
      and exists (
        select 1
        from public.instructor_billing_recoveries recovery
        where recovery.id = job.billing_recovery_id
          and recovery.status in ('recovered', 'closed')
      )
    returning job.id
  ), exhausted as (
    update public.instructor_service_notification_jobs job
    set status = 'failed',
        completed_at = now(),
        locked_at = null,
        last_error = coalesce(
          job.last_error,
          'Worker stopped before the final attempt completed'
        )
    where job.status = 'processing'
      and job.attempts >= 6
      and coalesce(job.locked_at, '-infinity'::timestamptz)
        < now() - greatest(p_lock_timeout, interval '1 minute')
    returning job.id
  ), candidates as (
    select job.id
    from public.instructor_service_notification_jobs job
    where job.attempts < 6
      and (
        (job.status = 'pending' and job.available_at <= now())
        or (
          job.status = 'processing'
          and coalesce(job.locked_at, '-infinity'::timestamptz)
            < now() - greatest(p_lock_timeout, interval '1 minute')
        )
      )
    order by job.available_at, job.id
    for update skip locked
    limit greatest(1, least(coalesce(p_limit, 10), 25))
  ), claimed as (
    update public.instructor_service_notification_jobs job
    set status = 'processing',
        attempts = job.attempts + 1,
        locked_at = now(),
        last_error = null
    from candidates
    where job.id = candidates.id
    returning job.*
  )
  select
    claimed.id,
    claimed.attempts,
    claimed.notification_type,
    claimed.instructor_profile_id,
    claimed.billing_recovery_id,
    claimed.delivered_to_email,
    claimed.login_email,
    profile.display_name,
    profile.slug,
    recovery.status,
    recovery.has_prior_successful_payment,
    recovery.first_failed_at,
    recovery.grace_ends_at
  from claimed
  join public.instructor_profiles profile
    on profile.id = claimed.instructor_profile_id
  left join public.instructor_billing_recoveries recovery
    on recovery.id = claimed.billing_recovery_id;
$$;

create or replace function public.complete_instructor_service_notification_job(
  p_job_id bigint,
  p_success boolean,
  p_provider_message_id text default null,
  p_error text default null,
  p_retryable boolean default false
)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  job public.instructor_service_notification_jobs;
  retry_seconds integer;
begin
  select * into job
  from public.instructor_service_notification_jobs
  where id = p_job_id
  for update;

  if job.id is null then
    raise exception 'Instructor service notification job not found';
  end if;
  if job.status = 'sent' then
    return 'sent';
  end if;
  if job.status <> 'processing' then
    raise exception 'Instructor service notification job is not processing';
  end if;

  if p_success then
    update public.instructor_service_notification_jobs
    set status = 'sent',
        provider_message_id = nullif(trim(p_provider_message_id), ''),
        sent_at = now(),
        completed_at = now(),
        locked_at = null,
        last_error = null
    where id = job.id;
    return 'sent';
  end if;

  if p_retryable and job.attempts < 6 then
    retry_seconds := least(
      1800,
      (30 * power(2, greatest(job.attempts - 1, 0)))::integer
    );
    update public.instructor_service_notification_jobs
    set status = 'pending',
        available_at = now() + retry_seconds * interval '1 second',
        locked_at = null,
        last_error = left(coalesce(p_error, 'Provider request failed'), 2000)
    where id = job.id;
    return 'pending';
  end if;

  update public.instructor_service_notification_jobs
  set status = 'failed',
      completed_at = now(),
      locked_at = null,
      last_error = left(coalesce(p_error, 'Provider request failed'), 2000)
  where id = job.id;
  return 'failed';
end;
$$;

create or replace function public.defer_instructor_service_notification_job(
  p_job_id bigint,
  p_error text,
  p_delay interval default interval '15 minutes'
)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  job public.instructor_service_notification_jobs;
begin
  select * into job
  from public.instructor_service_notification_jobs
  where id = p_job_id
  for update;

  if job.id is null then
    raise exception 'Instructor service notification job not found';
  end if;
  if job.status = 'sent' then
    return 'sent';
  end if;
  if job.status <> 'processing' then
    raise exception 'Instructor service notification job is not processing';
  end if;

  update public.instructor_service_notification_jobs
  set status = 'pending',
      attempts = greatest(attempts - 1, 0),
      available_at = now() + greatest(p_delay, interval '1 minute'),
      locked_at = null,
      last_error = left(
        coalesce(p_error, 'Notification provider is not configured'),
        2000
      )
  where id = job.id;

  return 'pending';
end;
$$;

