-- Durable instructor approval emails and failed-renewal recovery.
-- Established paying instructors receive a 14-day profile grace period.
-- Instructors without a positive paid invoice are paused immediately.

create table if not exists public.instructor_billing_recoveries (
  id uuid primary key default gen_random_uuid(),
  instructor_profile_id uuid not null
    references public.instructor_profiles(id) on delete cascade,
  stripe_customer_id text not null,
  stripe_subscription_id text not null,
  initial_stripe_invoice_id text not null unique,
  latest_stripe_invoice_id text not null,
  status text not null,
  has_prior_successful_payment boolean not null,
  first_failed_at timestamptz not null,
  last_failed_at timestamptz not null,
  grace_ends_at timestamptz,
  access_paused_at timestamptz,
  recovered_at timestamptz,
  closed_at timestamptz,
  failure_count integer not null default 1,
  last_stripe_event_id text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint instructor_billing_recovery_customer_check check (
    stripe_customer_id ~ '^cus_[A-Za-z0-9]+$'
  ),
  constraint instructor_billing_recovery_subscription_check check (
    stripe_subscription_id ~ '^sub_[A-Za-z0-9]+$'
  ),
  constraint instructor_billing_recovery_initial_invoice_check check (
    initial_stripe_invoice_id ~ '^in_[A-Za-z0-9]+$'
  ),
  constraint instructor_billing_recovery_latest_invoice_check check (
    latest_stripe_invoice_id ~ '^in_[A-Za-z0-9]+$'
  ),
  constraint instructor_billing_recovery_status_check check (
    status in ('grace_period', 'access_paused', 'recovered', 'closed')
  ),
  constraint instructor_billing_recovery_failure_count_check check (
    failure_count > 0
  ),
  constraint instructor_billing_recovery_grace_check check (
    (
      has_prior_successful_payment
      and grace_ends_at is not null
      and grace_ends_at > first_failed_at
    )
    or (
      not has_prior_successful_payment
      and grace_ends_at is null
    )
  )
);

create unique index if not exists instructor_billing_recovery_one_open
  on public.instructor_billing_recoveries (instructor_profile_id)
  where status in ('grace_period', 'access_paused');

create index if not exists instructor_billing_recovery_expiry_idx
  on public.instructor_billing_recoveries (grace_ends_at, id)
  where status = 'grace_period';

alter table public.membership_admin_events
  drop constraint if exists membership_admin_events_type_check;

alter table public.membership_admin_events
  add constraint membership_admin_events_type_check check (
    event_type in (
      'founding_assigned', 'guarantee_updated', 'guarantee_fulfilled',
      'claim_received', 'claim_reviewed', 'refund_verified', 'benefits_ended',
      'offer_redeemed', 'paid_invoice_recorded', 'guarantee_started',
      'billing_grace_started', 'first_payment_failed', 'billing_recovered',
      'billing_recovery_closed', 'billing_grace_expired'
    )
  );

create table if not exists public.instructor_service_notification_jobs (
  id bigint generated by default as identity primary key,
  instructor_profile_id uuid not null
    references public.instructor_profiles(id) on delete cascade,
  billing_recovery_id uuid
    references public.instructor_billing_recoveries(id) on delete cascade,
  notification_type text not null,
  dedupe_key text not null,
  delivered_to_email text not null,
  login_email text not null,
  status text not null default 'pending',
  attempts integer not null default 0,
  available_at timestamptz not null default now(),
  locked_at timestamptz,
  provider_message_id text,
  last_error text,
  sent_at timestamptz,
  completed_at timestamptz,
  created_at timestamptz not null default now(),
  constraint instructor_service_notification_type_check check (
    notification_type in (
      'profile_approved',
      'activation_payment_failed',
      'billing_grace_started',
      'billing_access_paused'
    )
  ),
  constraint instructor_service_notification_recovery_check check (
    (
      notification_type in ('profile_approved', 'activation_payment_failed')
      and billing_recovery_id is null
    )
    or (
      notification_type in ('billing_grace_started', 'billing_access_paused')
      and billing_recovery_id is not null
    )
  ),
  constraint instructor_service_notification_dedupe_check check (
    nullif(trim(dedupe_key), '') is not null
  ),
  constraint instructor_service_notification_email_check check (
    delivered_to_email ~ '^[^[:space:]@]+@[^[:space:]@]+[.][^[:space:]@]+$'
    and login_email ~ '^[^[:space:]@]+@[^[:space:]@]+[.][^[:space:]@]+$'
  ),
  constraint instructor_service_notification_status_check check (
    status in ('pending', 'processing', 'sent', 'failed', 'canceled')
  ),
  constraint instructor_service_notification_attempts_check check (
    attempts between 0 and 6
  ),
  constraint instructor_service_notification_unique
    unique (notification_type, dedupe_key)
);

create index if not exists instructor_service_notification_pending_idx
  on public.instructor_service_notification_jobs (status, available_at, id)
  where status in ('pending', 'processing');

create or replace function public.enqueue_instructor_profile_approval_email_if_ready(
  p_instructor_profile_id uuid
)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  profile public.instructor_profiles;
  recipient_email text;
  activation_ready boolean;
begin
  if p_instructor_profile_id is null then
    return 'invalid_profile';
  end if;

  select profile_record.* into profile
  from public.instructor_profiles profile_record
  where profile_record.id = p_instructor_profile_id;

  if profile.id is null or profile.status <> 'published'
    or profile.approved_at is null or profile.slug is null then
    return 'not_ready';
  end if;

  activation_ready := exists (
    select 1
    from public.instructor_lifetime_access access
    where access.instructor_profile_id = profile.id
  ) or (
    exists (
      select 1
      from public.instructor_memberships membership
      where membership.instructor_profile_id = profile.id
        and membership.status in ('active', 'trialing')
    )
    and not exists (
      select 1
      from public.instructor_offer_entitlements entitlement
      where entitlement.instructor_profile_id = profile.id
        and entitlement.redeemed_at is null
    )
  );

  if not activation_ready then
    return 'not_ready';
  end if;

  select lower(trim(account.email)) into recipient_email
  from public.accounts account
  where account.id = profile.account_id;

  if recipient_email is null
    or recipient_email !~ '^[^[:space:]@]+@[^[:space:]@]+[.][^[:space:]@]+$' then
    return 'recipient_missing';
  end if;

  insert into public.instructor_service_notification_jobs (
    instructor_profile_id,
    notification_type,
    dedupe_key,
    delivered_to_email,
    login_email
  ) values (
    profile.id,
    'profile_approved',
    profile.id::text,
    recipient_email,
    recipient_email
  ) on conflict (notification_type, dedupe_key) do nothing;

  if found then
    return 'queued';
  end if;
  return 'duplicate';
end;
$$;

